// 标点盲文编码——权威来源：
//   中文：GB/T 15720-2008《中国盲文》4.3 标点符号
//   英文：UEB (Unified English Braille) 标点表
// 值 = 每个"方"的点位数组组成的数组（多方式标点点位由多"方"组成）
// 注意：中文标点有的用"点5"作为标点引导符起始（GB/T 15720 规定标点前常用点5 引出）

// 中文标点（GB/T 15720-2008）：
//   句号(5,23) 逗号(5) 顿号(4) 分号(56) 冒号(36)
//   问号(5,3) 叹号(56,2) 省略号(5,5,5)
//   引号(56,235) 括号(5,2356 / 5,12356)
export const SYMBOLS_CN = {
  '。': [[5], [2, 3]],         // 句号：点5 + 点23
  '，': [[5]],                 // 逗号：点5
  '、': [[4]],                 // 顿号：点4
  '；': [[5, 6]],              // 分号：点56
  '：': [[3, 6]],              // 冒号：点36
  '？': [[5], [3]],            // 问号：点5 + 点3
  '！': [[5, 6], [2]],         // 叹号：点56 + 点2
  '…': [[5], [5], [5]],        // 省略号：点5×3
  '“': [[5, 6], [2, 3, 5]],    // 左引号
  '”': [[5, 6], [2, 3, 5]],    // 右引号
  '（': [[5], [2, 3, 5, 6]],   // 左括号
  '）': [[5], [1, 2, 3, 5, 6]] // 右括号
}

// 英文标点（UEB）：单方或两方
export const SYMBOLS_EN = {
  ',': [[2]],
  '.': [[2, 5, 6]],
  '?': [[2, 3, 6]],
  '!': [[2, 3, 4, 5, 6]],
  ';': [[2, 3]],
  ':': [[2, 5]],
  '“': [[6], [2]],
  '”': [[6], [5]],
  '(': [[6], [1, 2, 6]],
  ')': [[6], [3, 4, 5]]
}

const TABLES = { cn: SYMBOLS_CN, en: SYMBOLS_EN }

// 符号 → 点位（每方点集合的数组）。未知返回 null。
export function symbolToDots(lang, ch) {
  const table = TABLES[lang] || SYMBOLS_CN
  const entry = table[ch]
  return entry ? entry.map(f => [...f]) : null
}

